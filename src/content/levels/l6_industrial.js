function partBox(ctx, x, y, dir, a0, a1, b0, b1, z, h, colors) {
  const wx0 = dir > 0 ? x + a0 : x - a1, wx1 = dir > 0 ? x + a1 : x - a0;
  isoBox(ctx, 0, 0, wx0, y + b0, z, wx1 - wx0, b1 - b0, h, colors);
}
function makeForklift(o) {
  return {
    x: o.x0, y: o.y, dir: 1, pause: 0.5, speed: o.speed || 3, beepT: 0, removed: false, hits: new Map(), t: 0,
    depth() { return this.x + this.y; },
    update(world, dt) {
      this.t += dt;
      if (this.beepT > 0) this.beepT -= dt;
      if (this.pause > 0) { this.pause -= dt; if (this.pause <= 0) this.dir = this.x >= o.x1 - 0.01 ? -1 : 1; return; }
      this.x += this.dir * this.speed * dt;
      if (this.x >= o.x1) { this.x = o.x1; this.pause = 1.4; }
      if (this.x <= o.x0) { this.x = o.x0; this.pause = 1.4; }
      const p = world.player;
      if (p && this.beepT <= 0) {
        const along = (p.x - this.x) * this.dir;
        if (along > 0 && along < 5 && Math.abs(p.y - this.y) < 1.2) { world.sfx('horn', this); this.beepT = 2.5; }
      }
      for (const [f, tt] of this.hits) if (world.time - tt > 1.2) this.hits.delete(f);
      for (const f of world.fighters) {
        if (!f.alive || f.z > 0.6 || f.invuln > 0 || f.isDown || this.hits.has(f) || f.noclip) continue;
        const along = (f.x - this.x) * this.dir, across = f.y - this.y;
        if (along < -0.85 || along > 1.35 || Math.abs(across) > 0.48 + f.r) continue;
        this.hits.set(f, world.time);
        const side = across >= 0 ? 1 : -1;
        const def = { hz: 0.8, sfx: 'carHit', hitstop: 0.08, shake: 6 };
        const res = f.takeHit({ attacker: null, def, dmg: 14, dir: { x: this.dir * 0.6, y: side * 0.8 }, kb: 6, stun: 0.6, knockdown: true, launch: 4, unblockable: true, guardDmg: 0 }, world);
        world.onHit({ x: this.x, y: this.y }, f, def, res, 14);
        if (!f.isPlayer && world.player) world.addScore(200, f.x, f.y, 1, true);
      }
    },
    draw(ctx, world) {
      const x = this.x, y = this.y, d = this.dir;
      const s = toScreen(x, y, 0);
      shadow(ctx, s.x, s.y + 2, 26, 11, 0.4);
      const Y = '#e8b820';
      const parts = [
        [-0.8, -0.5, -0.38, 0.38, 0.15, 0.75, { color: '#3a3a40', outline: OL }],            // counterweight
        [-0.55, 0.45, -0.4, 0.4, 0.15, 0.55, { top: Y, left: shade2(Y, -0.12), right: shade2(Y, -0.32), outline: OL }],
        [-0.38, -0.1, -0.2, 0.2, 0.7, 0.28, { color: '#1a1a1e' }],                              // seat
        [0.48, 0.6, -0.34, 0.34, 0.1, 2.15, { color: '#4a4e56', outline: OL }],                 // mast
        [0.6, 1.35, -0.26, -0.14, 0.12, 0.06, { color: '#8a8e96' }],                            // forks
        [0.6, 1.35, 0.14, 0.26, 0.12, 0.06, { color: '#8a8e96' }],
      ];
      if (o.load) parts.push([0.65, 1.3, -0.38, 0.38, 0.18, 0.15, { color: '#b08a50', outline: OL }], [0.7, 1.25, -0.33, 0.33, 0.33, 0.6, { top: '#c89a5e', left: '#a87a48', right: '#7a5a34', outline: OL }]);
      parts.sort((a, b) => ((a[0] + a[1]) * d + (a[2] + a[3])) - ((b[0] + b[1]) * d + (b[2] + b[3])));
      for (const q of parts) partBox(ctx, x, y, d, q[0], q[1], q[2], q[3], q[4], q[5], q[6]);
      // driver
      const ds = toScreen(x - d * 0.22, y, 0.7);
      ctx.fillStyle = OL; ctx.fillRect(ds.x - 5, ds.y - 13, 10, 13);
      ctx.fillStyle = '#ff8a1a'; ctx.fillRect(ds.x - 4, ds.y - 12, 8, 11);
      ctx.fillStyle = '#d8d8c0'; ctx.fillRect(ds.x - 4, ds.y - 8, 8, 1);
      ellipse(ctx, ds.x, ds.y - 17, 4, 4, OL); ellipse(ctx, ds.x, ds.y - 17, 3, 3, '#e2a97a');
      ellipse(ctx, ds.x, ds.y - 20, 4, 2, '#f4f1e8');
      // overhead guard
      const posts = [[-0.48, -0.36], [-0.48, 0.36], [0.32, -0.36], [0.32, 0.36]];
      const tops = [];
      for (const [a, b] of posts) {
        const g0 = toScreen(x + a * d, y + b, 0.7), g1 = toScreen(x + a * d, y + b, 2.0);
        thick(ctx, g0.x, g0.y, g1.x, g1.y, 2, OL); tops.push(g1);
      }
      for (const [i, j] of [[0, 1], [1, 3], [3, 2], [2, 0], [0, 3]]) { line(ctx, tops[i].x, tops[i].y, tops[j].x, tops[j].y, '#2a2a30'); line(ctx, tops[i].x, tops[i].y - 1, tops[j].x, tops[j].y - 1, '#5a5e66'); }
      // beacon
      const bc = toScreen(x - d * 0.1, y, 2.1);
      const on = Math.floor(this.t * 5) % 2 === 0;
      ctx.fillStyle = OL; ctx.fillRect(bc.x - 2, bc.y - 4, 5, 4);
      ctx.fillStyle = on ? '#ffb030' : '#7a4a10'; ctx.fillRect(bc.x - 1, bc.y - 3, 3, 3);
      const L = (world.lightsDynamic ||= []);
      if (on) L.push({ x: x, y: y, z: 2, r: 2.6, color: '#ffb030', intensity: 0.5 });
      if (this.pause <= 0) L.push({ x: x + d * 1.6, y, z: 0.3, r: 2.6, color: '#fff0c0', intensity: 0.6 });
    },
  };
}
function shade2(hex, f) { // tiny local shade (avoid an extra import)
  const n = parseInt(hex.slice(1), 16), r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
  const c = v => Math.max(0, Math.min(255, Math.round(f < 0 ? v * (1 + f) : v + (255 - v) * f)));
  return '#' + ((1 << 24) | (c(r) << 16) | (c(g) << 8) | c(b)).toString(16).slice(1);
}

// ------------------------------------------------------------------ overhead crane (actor) — the lever drops its load
const CRANE = { y: 37.5, x0: 2.5, x1: 28.5, hookZ: 3.5, loadH: 0.7 };
function makeCrane() {
  return {
    x: 10, y: CRANE.y, dir: 1, pause: 0, removed: false, t: 0,
    load: { present: true, z: CRANE.hookZ - 0.8, vz: 0, falling: false, lower: 0 }, reloadT: 0,
    depth: () => 1e4,
    update(world, dt) {
      this.t += dt;
      if (this.pause > 0) this.pause -= dt;
      else {
        this.x += this.dir * 2.0 * dt;
        if (this.x > CRANE.x1) { this.x = CRANE.x1; this.dir = -1; this.pause = 0.8; }
        if (this.x < CRANE.x0) { this.x = CRANE.x0; this.dir = 1; this.pause = 0.8; }
      }
      const L = this.load;
      if (L.falling) {
        L.vz -= 26 * dt; L.z += L.vz * dt;
        if (L.z <= 0) this.impact(world);
      } else if (!L.present) {
        this.reloadT -= dt;
        if (this.reloadT <= 0) { L.present = true; L.lower = 1; L.z = CRANE.hookZ - 0.8; }
      }
      if (L.lower > 0) L.lower = Math.max(0, L.lower - dt * 1.5);
      if (L.falling) { L.x = L.x ?? this.x; } else L.x = this.x;
    },
    drop(world) {
      const L = this.load;
      if (!L.present || L.falling || L.lower > 0) { world.toast('NO LOAD ON THE HOOK - WAIT FOR IT'); return; }
      L.falling = true; L.vz = 0; L.x = this.x;
      world.sfx('clatter', { x: this.x, y: this.y });
      world.message('LOAD AWAY!', '', 0.8, '#ffd23a');
    },
    impact(world) {
      const L = this.load, x = L.x, y = this.y;
      L.falling = false; L.present = false; L.z = 0; this.reloadT = 4.5; L.x = undefined;
      world.camera.shake(9, 0.35);
      world.sfx('hitHeavy', { x, y }); world.sfx('wood', { x, y });
      world.fx.debris(x, y, 0.4, ['#a87a48', '#c89a5e', '#6e4a28'], 22);
      world.fx.dust(x, y, 0, 12);
      let crushed = 0;
      for (const f of world.fighters) {
        if (!f.alive || f.invuln > 0 || f.z > 1.2) continue;
        const d = Math.hypot(f.x - x, f.y - y);
        if (d > 1.15) continue;
        const def = { hz: 2, sfx: 'hitHeavy', hitstop: 0.1, shake: 8 };
        const res = f.takeHit({ attacker: null, def, dmg: 30, dir: { x: (f.x - x) / (d || 1) || 1, y: (f.y - y) / (d || 1) }, kb: 5, stun: 0.7, knockdown: true, launch: 3, unblockable: true, guardDmg: 0 }, world);
        world.onHit({ x, y }, f, def, res, 30);
        if (!f.isPlayer) { crushed++; world.addScore(300, f.x, f.y, 1, true); }
      }
      if (crushed) world.fx.popup(x, y, 1, crushed > 1 ? 'MULTI CRUSH!' : 'CRUSHED!', '#ffd23a', 1);
      for (const p of world.props) {
        if (p.type !== 'industrial_cage' || p.removed) continue;
        if (Math.abs(p.cx - x) < 1.05 && Math.abs(p.cy - y) < 1.05) {
          p.removed = true;
          world.fx.debris(p.cx, p.cy, 1, ['#8a9098', '#4a4e56', '#e8c040'], 18);
          world.sfx('metal', p);
          world.revealSecret('cage', p.cx, p.cy);
          world.rebuildPropGrid();
        }
      }
      if (Math.random() < 0.5) world.spawnItem(Math.random() < 0.5 ? 'industrial_tea' : 'cash5', x, y, 0.6, { vz: 4, vx: 1, pickDelay: 0.3 });
    },
    draw(ctx, world) {
      const hx = this.x, y = this.y;
      // bridge girder across the warehouse + trolley
      const a = toScreen(hx, 22.3, 4.6), b = toScreen(hx, 40.7, 4.6);
      thick(ctx, a.x, a.y, b.x, b.y, 5, OL); thick(ctx, a.x, a.y, b.x, b.y, 3, '#c8a020');
      for (let k = 0; k <= 18; k += 2) { const q = toScreen(hx, 22.5 + k, 4.6); ctx.fillStyle = '#1e1e22'; ctx.fillRect(q.x - 1, q.y - 1, 2, 2); }
      const tr = toScreen(hx, y, 4.6);
      ctx.fillStyle = OL; ctx.fillRect(tr.x - 8, tr.y - 4, 16, 9); ctx.fillStyle = '#4a4e56'; ctx.fillRect(tr.x - 7, tr.y - 3, 14, 7);
      const L = this.load;
      const hookZ = CRANE.hookZ + L.lower * 0.6;
      const hk = toScreen(hx, y, hookZ);
      line(ctx, tr.x - 1, tr.y + 5, hk.x - 1, hk.y, '#1a1a1e'); line(ctx, tr.x + 1, tr.y + 5, hk.x + 1, hk.y, '#5a5e66');
      ctx.fillStyle = OL; ctx.fillRect(hk.x - 4, hk.y, 8, 4); ctx.fillStyle = '#d8b020'; ctx.fillRect(hk.x - 3, hk.y + 1, 6, 2);
      thick(ctx, hk.x, hk.y + 4, hk.x, hk.y + 8, 2, OL); thick(ctx, hk.x, hk.y + 8, hk.x + 3, hk.y + 10, 2, OL);
      if (L.present || L.falling) {
        const lx = L.falling ? L.x : hx;
        const z = L.falling ? L.z : CRANE.hookZ - 0.85 + L.lower * 0.6;
        if (!L.falling) { // slings
          const c0 = toScreen(lx - 0.35, y - 0.35, z + CRANE.loadH), c1 = toScreen(lx + 0.35, y + 0.35, z + CRANE.loadH);
          line(ctx, hk.x, hk.y + 9, c0.x, c0.y, '#2a2a30'); line(ctx, hk.x, hk.y + 9, c1.x, c1.y, '#2a2a30');
        }
        isoBox(ctx, 0, 0, lx - 0.4, y - 0.4, z, 0.8, 0.8, 0.12, { color: '#b08a50', outline: OL });
        isoBox(ctx, 0, 0, lx - 0.36, y - 0.36, z + 0.12, 0.72, 0.72, CRANE.loadH - 0.12, { top: '#c89a5e', left: '#a87a48', right: '#7a5a34', outline: OL });
        const m = toScreen(lx, y + 0.37, z + 0.4); drawText(ctx, 'TEA', m.x - 2, m.y - 3, { color: '#3a2410', align: 'center' });
      }
    },
    drawShadow(ctx, world) {
      const L = this.load;
      if (!L.present && !L.falling) return;
      const lx = L.falling ? L.x : this.x;
      const s = toScreen(lx, this.y, 0);
      const z = L.falling ? L.z : CRANE.hookZ;
      const k = Math.max(0.3, 1 - z / 5);
      shadow(ctx, s.x, s.y, 14 * k + 6, 7 * k + 3, 0.45);
      if (Math.floor(world.time * 6) % 2) { ctx.fillStyle = '#ff3020'; ctx.fillRect(Math.round(s.x) - 1, Math.round(s.y) - 1, 3, 2); }
    },
  };
}

// ------------------------------------------------------------------ conveyor boxes (actors)
function makeBeltBoxes(belts) {
  return {
    x: 0, y: 0, removed: false, boxes: [], t: 0,
    update(world, dt) {
      this.t += dt;
      for (const b of belts) {
        b.t = (b.t ?? b.offset ?? 0) - dt;
        if (b.t <= 0) { b.t = b.every || 2.6; this.spawn(world, b); }
      }
    },
    spawn(world, b) {
      const box = {
        x: b.from[0], y: b.from[1], removed: false, belt: b, col: ['#a87a48', '#c89a5e', '#2e5aa0', '#9aa0a8'][Math.floor(Math.random() * 4)],
        depth() { return this.x + this.y; },
        update(w, dt) {
          const [dx, dy] = b.dir;
          this.x += dx * BELT_SPEED * dt; this.y += dy * BELT_SPEED * dt;
          const rem = (b.to[0] - this.x) * dx + (b.to[1] - this.y) * dy;
          if (rem <= 0) { this.removed = true; if (w.player && Math.hypot(w.player.x - this.x, w.player.y - this.y) < 10) { w.fx.dust(this.x, this.y, 0.3, 3); if (Math.random() < 0.3) w.sfx('wood', this); } }
        },
        draw(ctx) {
          const c = this.col;
          isoBox(ctx, 0, 0, this.x - 0.25, this.y - 0.25, 0.04, 0.5, 0.5, 0.4, { top: shade2(c, 0.15), left: c, right: shade2(c, -0.3), outline: OL });
          const t = toScreen(this.x, this.y + 0.26, 0.25); ctx.fillStyle = '#e8dcc0'; ctx.fillRect(t.x - 1, t.y - 4, 2, 6);
        },
      };
      world.addActor(box);
    },
  };
}

