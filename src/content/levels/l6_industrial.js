function openGroup(group) {
  return (world) => {
    for (const p of world.props) if (p.o.group === group) p.open = true;
    world.rebuildPropGrid();
  };
}

// A lorry backed onto the dock: 2-wide trailer (y..y+4) and cab (y+5..y+6), each tile its own prop segment.
function lorry(x, y, color, cabColor, text, stripe, textColor) {
  const out = [];
  for (let j = 0; j < 5; j++) for (let i = 0; i < 2; i++) out.push({ type: 'industrial_lorry', x: x + i, y: y + j, part: 'trailer', i, j, nw: 2, nd: 5, color, stripe, text, textColor });
  for (let j = 0; j < 2; j++) for (let i = 0; i < 2; i++) out.push({ type: 'industrial_lorry', x: x + i, y: y + 5 + j, part: 'cab', i, j, nw: 2, nd: 2, cabColor, h: 2.3 });
  return out;
}
