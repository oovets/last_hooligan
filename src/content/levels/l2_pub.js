    const inSnug = o => o.x >= 49 && o.x <= 54.5 && o.y >= 1 && o.y <= 7.5;
    world.pubSnugLights = world.lights.filter(inSnug);
    world.pubSnugHidden = world.items.filter(inSnug);
    for (const it of world.pubSnugHidden) it.draw = () => {};
