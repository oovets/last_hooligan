      if (k > 1) continue;
      const c = ['#ff3aa0', '#3ad8ff'][(x + y + Math.floor(t * 1.5)) % 2];
      ctx.globalAlpha = prev * (0.18 + 0.12 * Math.sin(t * 6 + x + y));
