  onUpdate(world) {
    const t = world.time;
    const snug = world.secrets.find(s => s.id === 'snug');
    const snugOpen = !snug || snug.found;
    for (const l of world.pubSnugLights || []) l.active = snugOpen;
    if (snugOpen && world.pubSnugHidden) { for (const it of world.pubSnugHidden) delete it.draw; world.pubSnugHidden = null; }
    for (const l of world.pubDisco || []) {
      const a = t * 0.9 + l.ph, rr = 2.2 + Math.sin(t * 0.7 + l.ph) * 0.9;
      l.x = DISCO_C.x + Math.cos(a) * rr; l.y = DISCO_C.y + Math.sin(a) * rr;
    }
  },
