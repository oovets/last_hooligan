          if (prevP) { ctx.fillStyle = '#2a2a24'; const dx = sp.x - prevP.x, dy = sp.y - prevP.y; for (let j = 0; j < 6; j++) ctx.fillRect(Math.round(prevP.x + dx * j / 6), Math.round(prevP.y + dy * j / 6), 1, 1); }
