const AWAY_ROWS = [[13, 34]], HOME_ROWS = [[36, 45]];
const onTerrace = (x, y) => x >= 33 && x <= 51 && y >= 13 && y < 46;
const inHome = (x, y) => x >= 37 && x <= 51 && y >= 36 && y < 46;

// ------------------------------------------------------------------ the crowd (non-combat actors on solid crowd tiles)
const SKINS = ['#e2a97a', '#d49a6a', '#f0c098', '#b87a50', '#8a5636', '#f4d0b0'];
const HAIRS = ['#141016', '#3a2717', '#6a4a2a', '#b4521c', '#e8d27a', '#5a5a5a'];
function makeFan(tx, ty, k, home) {
  const h = s => hash2(tx * 7 + k, ty * 13 + k * 3, s);
  const team = home ? [RIVAL.a, RIVAL.b] : [homeKit.main, homeKit.second];   // their lot in the rival club's colours, ours in black and yellow
  const jackets = home ? [RIVAL.a, '#1d2742', '#3a3a3e', '#b5a98a', RIVAL.b] : [homeKit.main, '#2b3a2a', '#1d2742', '#3a3a3e', homeKit.second, '#4a4030'];
  const armsR = h(5);
  return {
    skin: SKINS[Math.floor(h(1) * SKINS.length)], hair: HAIRS[Math.floor(h(2) * HAIRS.length)], hairH: 1 + Math.floor(h(3) * 3),
    jacket: jackets[Math.floor(h(4) * jackets.length)], shirt: team[0], trim: team[1], legs: h(9) < 0.5 ? '#2a3a5a' : '#1e1e26',
    arms: home ? (armsR < 0.35 ? 'point' : armsR < 0.6 ? 'clap' : armsR < 0.75 ? 'scarf' : 'down')
      : (armsR < 0.45 ? 'scarf' : armsR < 0.7 ? 'clap' : armsR < 0.8 ? 'point' : 'down'),
    hat: h(6) < 0.18 ? (h(7) < 0.5 ? team[0] : '#3a3a3e') : null,
    ph: h(8) * 6.28, tall: 0.92 + h(10) * 0.14, jumpy: h(11) < 0.35, scarfA: team[0], scarfB: team[1],
  };
}
function px(ctx, c, x, y, w, h) { ctx.fillStyle = c; ctx.fillRect(x, y, w, h); }
function drawFan(ctx, x, y, o, t, lean, hype) {
  const bounce = (o.jumpy || hype > 0.5) ? Math.round(Math.max(0, Math.sin(t * (5 + hype * 3) + o.ph)) * (2 + hype * 2)) : 0;
  const sway = Math.round(Math.sin(t * 1.7 + o.ph) * 1.2 + lean);
  x = Math.round(x + sway); y = Math.round(y - bounce);
  const s = o.tall;
  const top = y - Math.round(42 * s);
  const sh = y - Math.round(32 * s);                 // shoulders
  // legs
  px(ctx, OL, x - 5, sh + 15, 10, y - sh - 15);
  px(ctx, o.legs, x - 4, sh + 16, 3, y - sh - 17); px(ctx, o.legs, x + 1, sh + 16, 3, y - sh - 17);
  // arms (behind/around the torso)
  const wave = Math.sin(t * 3 + o.ph);
  if (o.arms === 'scarf') {
    const ay = top - 7 + Math.round(wave * 1.5);
    px(ctx, OL, x - 9, ay, 3, sh - ay + 3); px(ctx, OL, x + 6, ay, 3, sh - ay + 3);
    px(ctx, o.jacket, x - 8, ay + 1, 1, sh - ay + 1); px(ctx, o.jacket, x + 7, ay + 1, 1, sh - ay + 1);
    px(ctx, OL, x - 10, ay - 2, 20, 5);
    for (let i = 0; i < 9; i++) px(ctx, i % 2 ? o.scarfB : o.scarfA, x - 9 + i * 2, ay - 1, 2, 3);
    px(ctx, o.scarfB, x - 10, ay + 2, 1, 2); px(ctx, o.scarfB, x + 9, ay + 2, 1, 2);
  } else if (o.arms === 'point') {
    const ay = top + 2 + Math.round(wave * 2);
    px(ctx, OL, x + 5, ay - 1, 7, 3); px(ctx, OL, x + 5, ay, 3, sh - ay + 3);
    px(ctx, o.jacket, x + 6, ay, 5, 1); px(ctx, o.skin, x + 10, ay, 2, 1);
  } else if (o.arms === 'clap') {
    const c = Math.sin(t * 9 + o.ph) > 0 ? 0 : 2;
    px(ctx, OL, x + 2 + c, sh + 1, 7 - c, 4); px(ctx, o.skin, x + 7, sh + 2, 2, 2);
  }
  // torso
  px(ctx, OL, x - 7, sh - 1, 14, 18);
  px(ctx, o.jacket, x - 6, sh, 12, 16);
  px(ctx, o.shirt, x - 1, sh, 4, 8);
  px(ctx, o.trim, x - 6, sh + 4, 3, 1);
  if (o.arms === 'down') { px(ctx, OL, x - 8, sh + 1, 2, 13); px(ctx, OL, x + 6, sh + 1, 2, 13); }
  // head
  px(ctx, OL, x - 4, top - 1, 9, 11);
  px(ctx, o.skin, x - 3, top, 7, 9);
  if (o.hat) { px(ctx, o.hat, x - 3, top, 7, 3); px(ctx, o.trim, x - 3, top + 3, 7, 1); }
  else px(ctx, o.hair, x - 3, top, 7, o.hairH);
  px(ctx, '#140c0c', x + 1, top + 4, 1, 1); px(ctx, '#140c0c', x + 3, top + 4, 1, 1);
  const sing = Math.sin(t * 4 + o.ph * 0.5) > -0.2;
  px(ctx, '#4a1010', x + 1, top + 6, 2, sing ? 2 : 1);
}
function crowdActor(tx, ty, home) {
  const n = hash2(tx, ty, 91) < 0.35 ? 3 : 2;
  const spots = [[0.28, 0.32], [0.72, 0.7], [0.75, 0.22]].slice(0, n).sort((a, b) => (a[0] + a[1]) - (b[0] + b[1]));
  const fans = spots.map((sp, k) => ({ sp, o: makeFan(tx, ty, k, home) }));
  return {
    x: tx + 0.5, y: ty + 0.5, removed: false,
    depth() { return tx + ty + 1; },
    draw(ctx, world) {
      const c = toScreen(tx + 0.5, ty + 0.5);
      const cam = world.camera;
      if (Math.abs(c.x - cam.x) > 360 / cam.zoom || c.y - cam.y > 230 / cam.zoom || c.y - cam.y < -250 / cam.zoom) return;
      const S = world.__ae || {};
      const surge = (home ? S.surgeHome : S.surgeAway) || 0;
      const hype = Math.max(surge, S.hype || 0);
      for (const f of fans) {
        const p = toScreen(tx + f.sp[0], ty + f.sp[1]);
        drawFan(ctx, p.x, p.y, f.o, world.time, surge * 4, hype);
      }
    },
  };
}

// ------------------------------------------------------------------ crowd surge + coins from the home end
function sheltered(world, f) {
  if (f.z > 0.8) return true;                                       // standing on a barrier
  const W = world.map.w, tx = Math.floor(f.x), ty = Math.floor(f.y);
  for (let k = 1; k <= 3; k++) {
    const p = world.propAt[ty * W + tx - k];
    if (p && p.type === 'awayend_crushbarrier') return true;
  }
  return false;
}
function updateSurge(world, dt, S) {
  const p = world.player;
  if (!S.terrace || world.boss) { S.surgeAway = Math.max(0, (S.surgeAway || 0) - dt * 2); S.surgeHome = Math.max(0, (S.surgeHome || 0) - dt * 2); return; }
  S.surgeT -= dt;
  if (!S.surge && S.surgeT <= 0) {
    const home = inHome(p.x, p.y);
    S.surge = { t: 0, home, hit: new Set() };
    world.message('SURGE!', 'GET BEHIND A CRUSH BARRIER!', 1.6, '#ffe14a');
    world.sfx('crowdCheer', p);
  }
  const sg = S.surge;
  if (!sg) return;
  sg.t += dt;
  const lean = sg.t < 1.5 ? Math.min(1, sg.t / 1.5) * 0.4 : sg.t < 2.6 ? 1 : Math.max(0, 1 - (sg.t - 2.6) / 0.8);
  if (sg.home) S.surgeHome = lean; else S.surgeAway = lean;
  if (sg.t >= 1.5 && sg.t < 2.6) {
    const rows = sg.home ? HOME_ROWS : AWAY_ROWS;
    for (const f of world.fighters) {
      if (!f.alive || f.noclip || f.isDown || f.state === 'thrown') continue;
      if (f.x < 36.8 || f.x > 50.6 || !rows.some(([a, b]) => f.y >= a && f.y < b + 1)) continue;
      if (sheltered(world, f)) continue;
      world.moveEntity(f, 3.4 * dt, 0.4 * dt * Math.sin(world.time * 3 + f.id));
      if (!sg.hit.has(f) && sg.t > 1.75) {
        sg.hit.add(f);
        const res = f.takeHit({ attacker: null, def: { hz: 1, sfx: 'hitHeavy' }, dmg: f.isPlayer ? 6 : 10, dir: { x: 1, y: 0 }, kb: 4, stun: 0.5, knockdown: true, launch: 1, unblockable: true, guardDmg: 0 }, world);
        world.onHit({ x: f.x - 1, y: f.y }, f, { hz: 1, sfx: 'hitHeavy', shake: 3 }, res, 6);
      }
    }
    if (Math.random() < dt * 20) world.fx.dust(37 + Math.random() * 4, (sg.home ? 36 : 13) + Math.random() * (sg.home ? 10 : 22), 0, 2);
  }
  if (sg.t > 3.4) { S.surge = null; S.surgeT = 15 + Math.random() * 8; }
}
function updateCoins(world, dt, S) {
  const p = world.player;
  const enc = world.encounters.find(e => e.id === 'homeend');
  if (!p.alive || !inHome(p.x, p.y) || (enc && enc.state === 'cleared')) return;
  S.coinT -= dt;
  if (S.coinT > 0) return;
  S.coinT = 1.6 + Math.random() * 2.2;
  const crowd = world.map.markers.crowdH || [];
  if (!crowd.length) return;
  const c = crowd[Math.floor(Math.random() * crowd.length)];
  const thrower = { x: c.x + 0.4, y: c.y, z: 0.4, fx: 1, fy: 0, team: 'enemy', kind: 'crowd', name: 'HOME END' };
  const pr = world.spawnProjectile(thrower, 'awayend_coin', p.x + (Math.random() - 0.5) * 1.6, p.y + (Math.random() - 0.5) * 1.6, 4);
  if (pr) pr.z = 2.2;
  if (!S.coinTip) { S.coinTip = true; world.toast('COINS FROM THE HOME END - KEEP MOVING!'); }
}

function setScore(world, text) {
  const sb = world.props.find(p => p.o.scoreboard);
  if (sb) sb.o.text = text;
}

