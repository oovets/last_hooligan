function openProps(world, type, msg) {
  let n = 0;
  for (const p of world.props) if (p.type === type && !p.open) { p.open = true; n++; }
  if (n) { world.rebuildPropGrid(); world.sfx('door', world.player); if (msg) world.toast(msg); }
}

function pelican(world, p) {
  p.open = false;            // re-armable button
  p.greenT = 6;
  for (const h of world.hazards) if (h.type === 'traffic') h.t = Math.max(h.t, 6);
  world.sfx('menuSelect', p);
}

function bassDrop(world, p) {
  p.o.used = true;
  world.message('BASS DROP!', 'THE WHOLE CLUB GOES DOWN', 1.8, NEON.cyan);
  world.sfx('bossRoar', world.player);
  world.camera.shake(8, 0.6);
  world.fx.confetti(p.x + 0.5, p.y + 0.5, 1.5, DANCE_COLS, 30);
  for (const f of world.fighters) {
    if (f.team === 'player' || !f.alive || f.boss) continue;
    if (f.x < CLUB.x || f.x > CLUB.x1 || f.y < CLUB.y || f.y > CLUB.y1) continue;
    const dx = f.x - (p.x + 0.5), dy = f.y - (p.y + 0.5), d = Math.hypot(dx, dy) || 1;
    f.takeHit({ attacker: world.player, def: { hz: 1, sfx: 'hitHeavy' }, dmg: 14, dir: { x: dx / d, y: dy / d }, kb: 5, stun: 0.6, knockdown: true, launch: 3, unblockable: true, guardDmg: 0 }, world);
  }
}

